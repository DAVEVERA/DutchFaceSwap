export function getToolById(id: string): AITool {
  return AI_TOOLS.find((t) => t.id === id) || AI_TOOLS[0];
}

export function getSuiteTools(suiteId: ToolSuite): AITool[] {
  const suiteDef = TOOL_SUITES.find((s) => s.id === suiteId);
  if (!suiteDef) return [];
  return suiteDef.toolIds.map((id) => getToolById(id)).filter(Boolean);
}

export function getRelatedTools(tool: AITool, limit: number = 4): AITool[] {
  if (tool.suite) {
    const suiteTools = getSuiteTools(tool.suite).filter((t) => t.id !== tool.id);
    if (suiteTools.length >= limit) return suiteTools.slice(0, limit);
  }
  return AI_TOOLS.filter((t) => t.id !== tool.id && t.category === tool.category).slice(0, limit);
}

